#!/bin/sh
# Builds rs.c into myzel/src/js/dsp/rs-wasm.js (the module's bytes as base64; decoded in the AudioWorklet scope).
#   sh dev/tools/wasm/build.sh      (clang 18 with the wasm32 target and wasm-ld)
set -e
D=$(cd "$(dirname "$0")" && pwd); R=$(cd "$D/../../.." && pwd); T=$(mktemp -d)
clang --target=wasm32 -O3 -msimd128 -ffp-contract=off -fno-vectorize -fno-slp-vectorize -mllvm -disable-loop-idiom-all \
  -nostdlib -Wl,--no-entry -Wl,--import-memory -Wl,--strip-all -o "$T/rs.wasm" "$D/rs.c"
B=$(base64 -w0 "$T/rs.wasm")
cat > "$R/myzel/src/js/dsp/rs-wasm.js" <<JS
  // (Leistung, 24.10.2026) the live resampler in WebAssembly – generated by dev/tools/wasm/build.sh from rs.c there; do not
  // edit. The same sums as rd()'s JavaScript, bit for bit; used where the browser has WebAssembly with SIMD128
  const RS_WASM = '$B';
JS
rm -rf "$T"; echo "rs-wasm.js: $(printf %s "$B" | wc -c) base64 chars"
